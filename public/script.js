function addEditButton(container, messageIndex) {

    if (container.querySelector(".edit-message-button")) return;

    const editButton = document.createElement("button");

    editButton.className = "edit-message-button";
    editButton.innerHTML = "✏️ Edit";
    editButton.title = "Edit this message";

    editButton.addEventListener("click", () => {

        if (isSending) return;

        const message = conversationHistory[messageIndex];

        if (!message || message.role !== "user") return;

        const editedText = prompt(
            "Edit your message:",
            message.text
        );

        if (editedText === null) return;

        const cleanText = editedText.trim();

        if (cleanText === "") {
            alert("Message cannot be empty.");
            return;
        }

        if (cleanText === message.text) return;

        // Keep conversation before the edited message
        conversationHistory = conversationHistory.slice(0, messageIndex);

        // Update saved chat
        const currentChat = savedChats.find(
            chat => chat.id === currentChatId
        );

        if (currentChat) {
            currentChat.messages = [...conversationHistory];
            saveAllChats();
        }

        // Refresh chat display
        if (currentChat) {
            displayChat(currentChat);
        }

        // Send edited message
        input.value = cleanText;
        sendMessage();
    });

    container.appendChild(editButton);
}

// Stop generation
function stopGeneration() {

    if (abortController) {
        abortController.abort();
    }
}

// Render sidebar
function renderSidebar() {

    historyList.innerHTML = "";

    const searchQuery = chatSearchInput
        ? chatSearchInput.value.trim().toLowerCase()
        : "";

    const sortedChats = [...savedChats]
        .reverse()
        .filter(chat => {

            const titleMatch = chat.title
                .toLowerCase()
                .includes(searchQuery);

            const messageMatch = chat.messages.some(message =>
                message.text.toLowerCase().includes(searchQuery)
            );

            return titleMatch || messageMatch;
        });

    if (sortedChats.length === 0 && searchQuery !== "") {

        const emptyMessage = document.createElement("p");

        emptyMessage.textContent = "No chats found.";
        emptyMessage.style.fontSize = "12px";
        emptyMessage.style.color = "#888";
        emptyMessage.style.padding = "10px";

        historyList.appendChild(emptyMessage);
        return;
    }

    sortedChats.forEach(chat => {

        const chatItem = document.createElement("div");
        chatItem.classList.add("history-item");

        if (chat.id === currentChatId) {
            chatItem.classList.add("active");
        }

        // Chat title
        const title = document.createElement("span");
        title.classList.add("history-title");
        title.textContent = chat.title;

        // Options button
        const optionsButton = document.createElement("button");
        optionsButton.classList.add("chat-options-button");
        optionsButton.textContent = "⋮";
        optionsButton.title = "Chat options";
        optionsButton.setAttribute("aria-label", "Chat options");

        const optionsMenu = document.createElement("div");
        optionsMenu.classList.add("chat-options-menu");
        optionsMenu.hidden = true;

        // Rename
        const renameButton = document.createElement("button");
        renameButton.textContent = "Rename";

        renameButton.addEventListener("click", function(event) {

            event.stopPropagation();

            const newTitle = prompt(
                "Enter a new chat name:",
                chat.title
            );

            if (newTitle === null) return;

            const cleanTitle = newTitle.trim();

            if (cleanTitle === "") {
                alert("Chat name cannot be empty.");
                return;
            }

            chat.title = cleanTitle.slice(0, 50);

            saveAllChats();
            renderSidebar();
        });

        // Delete
        const deleteButton = document.createElement("button");
        deleteButton.textContent = "Delete";
        deleteButton.classList.add("delete-chat");

        deleteButton.addEventListener("click", function(event) {

            event.stopPropagation();

            const confirmed = confirm(
                "Are you sure you want to delete this chat?"
            );

            if (!confirmed) return;

            savedChats = savedChats.filter(
                item => item.id !== chat.id
            );

            if (currentChatId === chat.id) {
                startNewChat();
            }

            saveAllChats();
            renderSidebar();
        });

        optionsMenu.appendChild(renameButton);
        optionsMenu.appendChild(deleteButton);

        // Toggle menu
        optionsButton.addEventListener("click", function(event) {

            event.stopPropagation();

            const wasHidden = optionsMenu.hidden;

            document.querySelectorAll(".chat-options-menu").forEach(menu => {
                menu.hidden = true;
            });

            optionsMenu.hidden = !wasHidden;
        });

        // Open chat
        chatItem.addEventListener("click", function(event) {

            if (
                event.target.closest(".chat-options-button") ||
                event.target.closest(".chat-options-menu")
            ) {
                return;
            }

            displayChat(chat);
        });

        chatItem.appendChild(title);
        chatItem.appendChild(optionsButton);
        chatItem.appendChild(optionsMenu);

        historyList.appendChild(chatItem);
    });
}

// Create new chat
function createNewChat() {

    currentChatId = Date.now().toString();
    conversationHistory = [];

    savedChats.push({
        id: currentChatId,
        title: "New Chat",
        messages: []
    });

    saveAllChats();
    renderSidebar();
}

// Save current chat
function saveCurrentChat() {

    const chat = savedChats.find(
        item => item.id === currentChatId
    );

    if (chat) {

        chat.messages = [...conversationHistory];

        if (
            chat.title === "New Chat" &&
            conversationHistory.length > 0
        ) {
            chat.title = conversationHistory[0].text.slice(0, 30);
        }

        saveAllChats();
        renderSidebar();
    }
}

// Display saved chat
function displayChat(chat) {

    if (isSending) {
        stopGeneration();
    }

    currentChatId = chat.id;
    conversationHistory = [...chat.messages];

    chatArea.innerHTML = "";

    if (conversationHistory.length === 0) {

        chatArea.appendChild(welcomeMessage);

    } else {

        conversationHistory.forEach((item, index) => {

            const messageElement = document.createElement("div");

            if (item.role === "user") {

                messageElement.classList.add("user-message");
                messageElement.appendChild(
                    document.createTextNode(item.text)
                );

                // Add Edit button
                addEditButton(messageElement, index);

            } else {

                messageElement.classList.add("ai-message");
                messageElement.innerHTML = formatAIResponse(item.text);

                enhanceAIMessage(messageElement);
                addRegenerateButton(messageElement, index);
            }

            chatArea.appendChild(messageElement);
        });
    }

    input.value = "";
    chatArea.scrollTop = chatArea.scrollHeight;

    renderSidebar();
}

// Start new chat
function startNewChat() {

    if (isSending) {
        stopGeneration();
    }

    currentChatId = null;
    conversationHistory = [];

    chatArea.innerHTML = "";
    chatArea.appendChild(welcomeMessage);

    input.value = "";

    renderSidebar();
}

// Regenerate AI response
async function regenerateResponse(messageElement, modelIndex, button) {

    if (isSending) return;

    const userIndex = modelIndex - 1;

    if (
        userIndex < 0 ||
        conversationHistory[userIndex]?.role !== "user" ||
        conversationHistory[modelIndex]?.role !== "model"
    ) {
        return;
    }

    const chatIdAtStart = currentChatId;
    const userText = conversationHistory[userIndex].text;
    const previousHistory = conversationHistory.slice(0, userIndex);

    isSending = true;
    abortController = new AbortController();

    button.disabled = true;
    button.textContent = "Generating...";

    sendButton.disabled = false;
    sendButton.innerHTML = "Stop";
    sendButton.title = "Stop generation";

    messageElement.innerHTML = `
        <div class="typing-indicator">
            <span></span>
            <span></span>
            <span></span>
        </div>
    `;

    try {

        const response = await fetch("/chat", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                message: userText,
                history: previousHistory
            }),
            signal: abortController.signal
        });

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "Something went wrong.");
        }

        if (currentChatId !== chatIdAtStart) return;

        const newReply = data.reply || "No response received.";

        conversationHistory = [
            ...previousHistory,
            {
                role: "user",
                text: userText
            },
            {
                role: "model",
                text: newReply
            }
        ];

        messageElement.innerHTML = formatAIResponse(newReply);

        enhanceAIMessage(messageElement);

        addRegenerateButton(
            messageElement,
            conversationHistory.length - 1
        );

        saveCurrentChat();

    } catch (error) {

        if (error.name === "AbortError") {

            messageElement.textContent = "Generation stopped.";

        } else {

            console.error("Nova AI Error:", error);

            let errorMessage = "Something went wrong. Please try again.";

            if (!navigator.onLine) {
                errorMessage = "You are offline. Please check your internet connection.";
            } else if (error instanceof TypeError) {
                errorMessage = "Unable to connect to Nova AI. Please check your internet connection.";
            } else if (error.message.includes("429")) {
                errorMessage = "Too many requests. Please wait a moment and try again.";
            } else if (error.message.includes("503")) {
                errorMessage = "AI service is temporarily unavailable. Please try again later.";
            }

            messageElement.textContent = errorMessage;
        }

    } finally {

        isSending = false;
        abortController = null;

        sendButton.disabled = false;
        sendButton.innerHTML = originalSendButtonHTML;
        sendButton.title = "";

        chatArea.scrollTop = chatArea.scrollHeight;
    }
}

// Send message
async function sendMessage() {

    const message = input.value.trim();

    if (message === "" || isSending) return;

    if (!currentChatId) {
        createNewChat();
    }

    isSending = true;
    abortController = new AbortController();

    sendButton.disabled = false;
    sendButton.innerHTML = "Stop";
    sendButton.title = "Stop generation";

    if (welcomeMessage.parentNode) {
        welcomeMessage.remove();
    }

    // User message
    const userMessage = document.createElement("div");
    userMessage.classList.add("user-message");
    userMessage.appendChild(document.createTextNode(message));

    // Add Edit button
    addEditButton(userMessage, conversationHistory.length);

    chatArea.appendChild(userMessage);

    input.value = "";
    chatArea.scrollTop = chatArea.scrollHeight;

    // AI typing indicator
    const aiMessage = document.createElement("div");
    aiMessage.classList.add("ai-message");

    aiMessage.innerHTML = `
        <div class="typing-indicator">
            <span></span>
            <span></span>
            <span></span>
        </div>
    `;

    chatArea.appendChild(aiMessage);

    try {

        const response = await fetch("/chat", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                message: message,
                history: conversationHistory
            }),
            signal: abortController.signal
        });

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "Something went wrong.");
        }

        const reply = data.reply || "No response received.";

        aiMessage.innerHTML = formatAIResponse(reply);

        enhanceAIMessage(aiMessage);

        conversationHistory.push({
            role: "user",
            text: message
        });

        conversationHistory.push({
            role: "model",
            text: reply
        });

        addRegenerateButton(
            aiMessage,
            conversationHistory.length - 1
        );

        saveCurrentChat();

    } catch (error) {

        console.error("Nova AI Error:", error);

        if (error.name === "AbortError") {

            aiMessage.textContent = "Generation stopped.";

        } else {

            let errorMessage = "Something went wrong. Please try again.";

            if (!navigator.onLine) {
                errorMessage = "You are offline. Please check your internet connection.";
            } else if (error instanceof TypeError) {
                errorMessage = "Unable to connect to Nova AI. Please check your internet connection.";
            } else if (error.message.includes("429")) {
                errorMessage = "Too many requests. Please wait a moment and try again.";
            } else if (error.message.includes("503")) {
                errorMessage = "AI service is temporarily unavailable. Please try again later.";
            }

            aiMessage.textContent = errorMessage;
        }

    } finally {

        isSending = false;
        abortController = null;

        sendButton.disabled = false;
        sendButton.innerHTML = originalSendButtonHTML;
        sendButton.title = "";

        chatArea.scrollTop = chatArea.scrollHeight;
    }
}

// Send or Stop button
sendButton.addEventListener("click", function() {

    if (isSending) {
        stopGeneration();
    } else {
        sendMessage();
    }
});

// Enter key
input.addEventListener("keydown", function(event) {

    if (event.key === "Enter") {
        sendMessage();
    }
});

// New Chat button
newChatButton.addEventListener("click", startNewChat);

// Search chats
if (chatSearchInput) {

    chatSearchInput.addEventListener("input", function() {
        renderSidebar();
    });
}

// Restore last saved chat
if (savedChats.length > 0) {

    displayChat(savedChats[savedChats.length - 1]);

} else {

    renderSidebar();
}



// Get HTML elements
const input = document.querySelector(".input-area input");
const sendButton = document.querySelector(".send-button");
const chatArea = document.querySelector(".chat-area");
const welcomeMessage = document.querySelector(".welcome-message");
const newChatButton = document.querySelector(".new-chat");
const historyList = document.querySelector(".history-list");
const exportChatButton = document.querySelector("#exportChatButton");
const chatSearchInput = document.querySelector("#chatSearchInput");

let isSending = false;
let abortController = null;

const originalSendButtonHTML = sendButton.innerHTML;

// Load saved chats
let savedChats = loadChats();
let currentChatId = null;
let conversationHistory = [];

// Save all chats
function saveAllChats() {
    saveChats(savedChats);
}

// Export current chat
function exportCurrentChat() {

    if (conversationHistory.length === 0) {
        alert("There are no messages to export.");
        return;
    }

    const currentChat = savedChats.find(
        chat => chat.id === currentChatId
    );

    const chatTitle = currentChat
        ? currentChat.title
        : "Nova AI Chat";

    let exportText = "";

    exportText += "====================================\n";
    exportText += "             NOVA AI CHAT\n";
    exportText += "====================================\n\n";
    exportText += "Chat Title: " + chatTitle + "\n";
    exportText += "Exported: " + new Date().toLocaleString() + "\n\n";
    exportText += "------------------------------------\n\n";

    conversationHistory.forEach(item => {

        if (item.role === "user") {
            exportText += "YOU:\n";
        } else if (item.role === "model") {
            exportText += "NOVA AI:\n";
        }

        exportText += item.text + "\n\n";
        exportText += "------------------------------------\n\n";
    });

    exportText += "End of Conversation\n";
    exportText += "Generated by Nova AI\n";

    const blob = new Blob([exportText], {
        type: "text/plain;charset=utf-8"
    });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");

    const safeFileName = chatTitle
        .replace(/[<>:"/\\|?*]/g, "")
        .trim()
        .replace(/\s+/g, "_")
        .slice(0, 50) || "Nova_AI_Chat";

    link.href = url;
    link.download = safeFileName + ".txt";

    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    URL.revokeObjectURL(url);
}

if (exportChatButton) {
    exportChatButton.addEventListener("click", exportCurrentChat);
}

// Format AI response
function formatAIResponse(text) {

    if (!window.marked || !window.DOMPurify) {
        return text;
    }

    const html = marked.parse(text, {
        breaks: true,
        gfm: true
    });

    return DOMPurify.sanitize(html);
}

// Copy Code buttons
function addCopyButtons(container) {

    const codeBlocks = container.querySelectorAll("pre");

    codeBlocks.forEach(block => {

        if (block.querySelector(".copy-code-button")) return;

        const button = document.createElement("button");
        button.className = "copy-code-button";
        button.textContent = "Copy Code";

        button.addEventListener("click", async () => {

            const code = block.querySelector("code") || block;

            try {

                await navigator.clipboard.writeText(code.innerText);
                button.textContent = "Copied!";

                setTimeout(() => {
                    button.textContent = "Copy Code";
                }, 2000);

            } catch (error) {
                button.textContent = "Copy failed";
            }
        });

        block.style.position = "relative";
        block.appendChild(button);
    });
}

// Syntax highlighting
function highlightCodeBlocks(container) {

    if (!window.hljs) return;

    const codeBlocks = container.querySelectorAll("pre code");

    codeBlocks.forEach(block => {
        hljs.highlightElement(block);
    });
}

// Enhance AI message
function enhanceAIMessage(container) {
    addCopyButtons(container);
    highlightCodeBlocks(container);
}

// Add Copy, Regenerate and Feedback buttons
function addRegenerateButton(container, modelIndex) {

    if (container.querySelector(".response-actions")) return;

    const actions = document.createElement("div");
    actions.className = "response-actions";

    // Copy button
    const copyButton = document.createElement("button");
    copyButton.className = "response-action-button";
    copyButton.innerHTML = "📋 Copy";
    copyButton.title = "Copy AI response";

    copyButton.addEventListener("click", async () => {

        const responseText = conversationHistory[modelIndex]?.text;

        if (!responseText) return;

        try {

            await navigator.clipboard.writeText(responseText);
            copyButton.innerHTML = "✓ Copied!";

            setTimeout(() => {
                copyButton.innerHTML = "📋 Copy";
            }, 2000);

        } catch (error) {
            copyButton.innerHTML = "Copy failed";
        }
    });

    // Regenerate button
    const regenerateButton = document.createElement("button");
    regenerateButton.className = "response-action-button regenerate-button";
    regenerateButton.innerHTML = "↻ Regenerate";
    regenerateButton.title = "Generate a new response";

    regenerateButton.addEventListener("click", () => {
        regenerateResponse(container, modelIndex, regenerateButton);
    });

    // Helpful button
    const helpfulButton = document.createElement("button");
    helpfulButton.className = "response-action-button feedback-button";
    helpfulButton.innerHTML = "👍";
    helpfulButton.title = "Helpful";
    helpfulButton.setAttribute("aria-label", "Helpful");

    // Not helpful button
    const notHelpfulButton = document.createElement("button");
    notHelpfulButton.className = "response-action-button feedback-button";
    notHelpfulButton.innerHTML = "👎";
    notHelpfulButton.title = "Not helpful";
    notHelpfulButton.setAttribute("aria-label", "Not helpful");

    helpfulButton.addEventListener("click", () => {
        helpfulButton.classList.toggle("selected");
        notHelpfulButton.classList.remove("selected");
    });

    notHelpfulButton.addEventListener("click", () => {
        notHelpfulButton.classList.toggle("selected");
        helpfulButton.classList.remove("selected");
    });

    actions.appendChild(copyButton);
    actions.appendChild(regenerateButton);
    actions.appendChild(helpfulButton);
    actions.appendChild(notHelpfulButton);

    container.appendChild(actions);
}

